def _get_forced_aibi_roads(road_info, current_time=None):
    forced_roads = set()
    for cross_id in aibi_road:
        Cross_id = str(cross_id)
        if Cross_id not in road_info:
            continue

        _, road_state_report = get_forced_state(
            Cross_id,
            "0",
            road_info,
            current_time=current_time,
        )
        if road_state_report and road_state_report.get("forced"):
            forced_roads.add(cross_id)

    return forced_roads





def get_global_online_intersection_config(cross_id):
    from Lambdas import get_online_intersection_config

    cross_id = str(cross_id)
    cross_id_int = int(cross_id) if cross_id.isdigit() else cross_id
    config = get_online_intersection_config(cross_id)
    global_rows = []
    missing_from_global_map = []

    for row in config["intersection_to_rid_lambda"]:
        rid = row["rid"]
        direction = None
        in_global_map = False

        mapping = online_map_info.get(rid)
        if isinstance(mapping, dict):
            if cross_id_int in mapping:
                direction = mapping[cross_id_int]
                in_global_map = True
            elif cross_id in mapping:
                direction = mapping[cross_id]
                in_global_map = True
        elif isinstance(mapping, list) and len(mapping) >= 2:
            if str(mapping[0]) == cross_id:
                direction = mapping[1]
                in_global_map = True

        global_row = dict(row)
        global_row["online_map_info_direction"] = direction
        global_row["in_online_map_info"] = in_global_map
        global_rows.append(global_row)

        if not in_global_map:
            missing_from_global_map.append(rid)

    config.update({
        "in_intern_road_id": cross_id_int in intern_road_id,
        "global_online_map_info": global_rows,
        "missing_from_online_map_info": missing_from_global_map,
    })
    return config

def get_min_sub(a1,a2,b1,b2):
    min_Sub =10000
    ret = [0,0]
    if abs(a1-b1)<min_Sub:
        ret = [a1,b1]
        min_Sub = abs(a1-b1)
    if abs(a2-b2)<min_Sub:
        ret = [a1,b1]
        min_Sub = abs(a2-b2)
    if abs(a1-b2)<min_Sub:
        ret = [a1,b2]
        min_Sub = abs(a1-b2)
    if abs(a2-b1)<min_Sub:
        ret = [a2,b1]
    return ret[0],ret[1]


