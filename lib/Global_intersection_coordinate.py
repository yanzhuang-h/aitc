def coordinate_internet_roads(result_action_map, coordinate_map_set,
                              online_data_map, OverFlow, extend_map=None):
    """Process only pure-internet intersections, then shared final rules.

    Inputs and output have exactly the same format as :func:`coordinate`.
    ``intern_road_id`` is the selected road set. Green-wave coordination is
    disabled so this function is safe for an external orchestrator to call.
    """
    return coordinate(
        result_action_map, coordinate_map_set, online_data_map, OverFlow,
        extend_map, enabled_processors={ROAD_PROCESSOR_INTERNET},
        include_green_wave=False,
    )


def coordinate_mixed_roads(result_action_map, coordinate_map_set,
                           online_data_map, OverFlow, extend_map=None):
    """Process video plus traffic mixed intersections.

    The selected set is ``shipin_road`` (plus historically forced AIBI roads
    when the existing mixed processor includes them). Inputs and output use
    the same ten-element plan format as :func:`coordinate`; green wave is off.
    """
    return coordinate(
        result_action_map, coordinate_map_set, online_data_map, OverFlow,
        extend_map, enabled_processors={ROAD_PROCESSOR_MIXED},
        include_green_wave=False,
    )


def coordinate_flow_roads(result_action_map, coordinate_map_set,
                          online_data_map, OverFlow, extend_map=None):
    """Process only pure-flow intersections from ``shipin1_road``.

    Inputs and output use the same ten-element plan format as :func:`coordinate`.
    Common post-processing is retained and green-wave coordination is disabled.
    """
    return coordinate(
        result_action_map, coordinate_map_set, online_data_map, OverFlow,
        extend_map, enabled_processors={ROAD_PROCESSOR_FLOW},
        include_green_wave=False,
    )


def coordinate_without_green_wave(result_action_map, coordinate_map_set,
                                  online_data_map, OverFlow, extend_map=None):
    """Run all three road processors while excluding green-wave processing.

    This is the recommended global entry point for the future model
    orchestrator. It preserves the legacy processor order and all shared rules.
    """
    return coordinate(
        result_action_map, coordinate_map_set, online_data_map, OverFlow,
        extend_map, enabled_processors=ALL_ROAD_PROCESSORS,
        include_green_wave=False,
    )
