    ret = [0,0]
    if abs(a1-b1)<min_Sub:
        ret = [a1,b1]
        min_Sub = abs(a1-b1)
    if abs(a2-b2)<min_Sub:
        ret = [a1,b1]
        min_Sub = abs(a2-b2)
    if abs(a1-b2)<min_Sub:
        ret = [a1,b2]
        min_Sub = abs(a1-b2)
    if abs(a2-b1)<min_Sub:
        ret = [a2,b1]
    return ret[0],ret[1]


